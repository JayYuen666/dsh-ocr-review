#!/usr/bin/env node
/// <reference types="node" />
// 构建 host.js：rolldown 把 host.ts 及其 `./lib/*` 依赖打成单文件 ESM，落在**包根**
// （与源码同目录，故 `import.meta.dirname` 的语义与源码态完全一致）。
// 为什么必须有这一步：Node 对 node_modules 里的 .ts 直接抛
// ERR_UNSUPPORTED_NODE_MODULES_TYPE_STRIPPING（实测），而发布出去的包正是躺在
// node_modules 里被 dsh 载入的；官方示例包（docs/user/develop/basic/publish.zh.md
// 的 hello-plugin）也是包根放 index.js 产物。本仓 host.ts + client.js 同形态。
// 不产 .d.ts：插件包对外没有 TS API——dsh 按包名载入运行，没有人 import 它。
// 顶部 node reference：oxlint 类型检查对 .mjs 不自动加载 @types/node，需显式声明
// 才能解析 node:fs/promises、process、import.meta（否则整文件按 error 类型误报 unsafe）。
import { readFile, rename, writeFile } from "node:fs/promises";
import { realpathSync } from "node:fs";
import path from "node:path";
import { rolldown } from "rolldown";
import { canonicalizeRegionPaths } from "@jayyuen66/dsh-plugin-shared/lib/canonicalize-region-paths";

const root = import.meta.dirname;

/**
 * 读本包 package.json，带上下文的失败信息。
 *
 * 为什么惰性而不是模块顶层 await：顶层一次 JSON 语法错误会以未捕获的顶层 await 错误
 * + 裸 SyntaxError 收场，用户看不出是哪个文件坏了；而 test/host-freshness.ts 仅仅为了
 * 拿 buildHost 就得连带读盘，包名一坏整个夹具 import 就先失败。
 * @returns {Promise<unknown>}
 */
async function readPackageJson() {
  const file = path.join(root, "package.json");
  try {
    return JSON.parse(await readFile(file, "utf8"));
  } catch (error) {
    throw new Error(`build-host：读 ${file} 失败：${String(error)}`, { cause: error });
  }
}

/**
 * 从 JSON.parse 的 unknown 投影为 Record（非对象 → 空对象兜底），避免 any 索引。
 * @param {unknown} raw
 * @returns {Record<string, unknown>}
 */
function asRecord(raw) {
  if (raw !== null && typeof raw === "object" && !Array.isArray(raw)) {
    return raw;
  }
  return {};
}

/**
 * 取依赖表里的包名清单（值即外部化说明符）。
 * @param {string} field
 * @returns {string[]}
 */
function dependencyNames(pkgJson, field) {
  const table = asRecord(asRecord(pkgJson)[field]);
  return Object.keys(table).filter((name) => typeof table[name] === "string");
}

/**
 * dependencies / peerDependencies / optionalDependencies 一律外部化：它们由 pnpm 真实
 * 安装，产物里保留裸说明符才拿得到单例（内联会把 shared 的模块级状态复制成多份）。
 * 子路径说明符同样要外部化——external 的字符串项是精确匹配，所以按「包名段」判定
 * 而不是枚举子路径。optionalDependencies 必须一起算：@alibaba-group/open-code-review
 * 今天没被内联只是因为 lib/cli.ts 用 createRequire(import.meta.url).resolve() 取
 * launcher、rolldown 不解析这种形态——一旦有人改成动态 import，整包连同它的平台
 * 二进制选择逻辑会被内联进 host.js，import.meta.url 也随之从依赖目录变成包根。
 * @param {unknown} pkgJson
 * @returns {Set<string>}
 */
function externalNamesFor(pkgJson) {
  return new Set([
    ...dependencyNames(pkgJson, "dependencies"),
    ...dependencyNames(pkgJson, "peerDependencies"),
    ...dependencyNames(pkgJson, "optionalDependencies"),
  ]);
}

/**
 * 说明符的包名段：`@scope/pkg/sub` → `@scope/pkg`，`pkg/sub` → `pkg`。
 * @param {string} id
 * @returns {string}
 */
function packageNameOf(id) {
  const segments = id.split("/");
  if (id.startsWith("@")) {
    return segments.slice(0, 2).join("/");
  }
  return segments[0] ?? id;
}

/**
 * 生成 host.js 的完整文本。
 * @returns {Promise<string>}
 */
export async function buildHost() {
  const externalNames = externalNamesFor(await readPackageJson());
  const bundle = await rolldown({
    input: path.join(root, "host.ts"),
    external: (id) => externalNames.has(packageNameOf(id)),
    platform: "node",
    resolve: { extensions: [".ts", ".mjs", ".js"] },
  });
  let code;
  try {
    const { output } = await bundle.generate({ format: "esm" });
    const chunk = output.find((item) => item.type === "chunk");
    if (chunk === undefined) {
      throw new Error("rolldown generate returned no chunk output");
    }
    // 产物是单文件，多余 chunk / asset 不落盘 ⇒ 宿主加载时才因缺模块而炸。
    // 这里失败比运行时失败早，且错因指向构建而不是宿主。
    const chunkCount = output.filter((item) => item.type === "chunk").length;
    if (chunkCount > 1) {
      throw new Error(`rolldown 产出 ${chunkCount} 个 chunk，单文件产物只支持一块`);
    }
    if (output.some((item) => item.type === "asset")) {
      throw new Error("rolldown 产出了 asset，单文件产物没有落盘它的位置");
    }
    // `//#region` 行的路径由 rolldown 按 process.cwd() 算出 ⇒ 同一份源码有两种字节（cwd=包根 写
    // `lib/x.ts`，cwd=plugins/ 写 `<包名>/lib/x.ts`）。折成 canonical 必须落在**返回值之前**：
    // test/host-freshness.ts 拿内存构建与磁盘产物逐字节比，只在一侧折就永远红。
    code = canonicalizeRegionPaths(chunk.code.trimEnd(), root);
  } finally {
    // bundle 持有原生资源，不 close 会在重复构建（测试每次都构建）与异常路径上持续泄漏。
    await bundle.close();
  }
  return `// GENERATED by build-host.mjs — edit host.ts / lib/*.ts, then run \`node build-host.mjs\`.\n${code}\n`;
}

async function main() {
  const out = await buildHost();
  const target = path.join(root, "host.js");
  // 同目录临时文件 + rename：rename 在同一文件系统内是原子的，中断/OOM 只会留下
  // 临时文件，不会把 host.js 截断成半份 ESM——后者要等到宿主加载时才炸。
  const tmp = `${target}.${process.pid}.tmp`;
  await writeFile(tmp, out, "utf8");
  await rename(tmp, target);
  console.info("host.js written:", out.length, "chars");
}

/**
 * 直跑守卫：argv[1] 与本文件按 **realpath** 逐字比。pnpm 等场景 argv[1] 可能是
 * 符号链接路径，裸字符串比较会让直跑分支被静默跳过。
 * argv[1] 缺席（node -e 一类）时 realpath 会抛，同样落进"非直跑"。
 * @returns {boolean}
 */
function invokedDirectly() {
  try {
    return realpathSync(process.argv[1]) === realpathSync(import.meta.filename);
  } catch {
    return false;
  }
}

if (invokedDirectly()) {
  try {
    await main();
  } catch (error) {
    console.error(error);
    process.exitCode = 1;
  }
}
