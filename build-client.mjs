#!/usr/bin/env node
// @ts-check
/// <reference types="node" />
// 构建 client.js：rolldown 把 src/client-entry.ts 打包为 CJS（react 家族精确外置），再包进
// window.__ModuleLoader__.load({ id, factory }) UMD 外壳。id 取 package.json 的 name，
// 与 dsh.client 模块表键一致。
// 编排（外置判据、store 路径折叠、外壳拼装）统一住在 @jayyuen66/dsh-plugin-shared/
// lib/build-client；本文件只声明入口、生成头与本仓自有的包名同源校验。
// 运行：node build-client.mjs（或 pnpm build:client）。buildClient() 供测试导入。
import path from "node:path";
import { rolldown } from "rolldown";
import { buildClientBundle } from "@jayyuen66/dsh-plugin-shared/lib/build-client";
import { invokedDirectly, writeArtifact } from "@jayyuen66/dsh-plugin-shared/lib/build-artifacts";

export { singleEntryChunk } from "@jayyuen66/dsh-plugin-shared/lib/build-artifacts";

const root = import.meta.dirname;

/** 生成 client.js 的完整文本（含 ModuleLoader 外壳）。 */
export async function buildClient() {
  return buildClientBundle({
    root,
    rolldown,
    header:
      "// GENERATED by buildClient() in build-client.mjs — edit src/client-entry.ts, then run `node build-client.mjs`.",
    verifyName: ({ pkgName, body }) => {
      // 槽 key、descriptor id 与 `$mount` 的 package 位的包名同源：唯一定义在
      // lib/remote-shape.ts 的 OCR_BUNDLE_PACKAGE，src 侧只引常量、不再自带字面量。宿主按
      // 包名逐字匹配槽 key，对不上就是整张卡静默不渲染——而包名改名在别的环节没有症状。
      // 判据是**带引号的字面量**而不是裸子串：裸 `includes` 会被任何「包含包名」的文本满足
      // （导入路径、注释、更长的包名），而这里要证的是「chunk 里恰好有一处 `"<pkg>"` 字符串
      // 字面量等于 package.json 的 name」。恰好 1 次 = 常量定义处这一处；0 次说明常量值与
      // package.json 的 name 已经分叉；超过 1 次说明有人绕开常量重新内联了字面量（两份
      // 各自漂移的起点），都不放行。
      const quotedName = JSON.stringify(pkgName);
      const nameOccurrences = body.split(quotedName).length - 1;
      if (nameOccurrences !== 1) {
        throw new Error(
          `build-client：产物里带引号的包名字面量 ${quotedName} 出现 ${nameOccurrences} 次` +
            "（期望恰好 1 次：lib/remote-shape.ts 的 OCR_BUNDLE_PACKAGE 定义处），" +
            "src 侧的包名没有收敛到这个常量，或常量值与 package.json 的 name 已分叉。",
        );
      }
    },
  });
}

async function main() {
  const out = await buildClient();
  await writeArtifact(path.join(root, "client.js"), out);
  console.info("client.js written:", Buffer.byteLength(out, "utf8"), "bytes");
}

if (invokedDirectly(import.meta.filename)) {
  try {
    await main();
  } catch (error) {
    console.error(error);
    process.exitCode = 1;
  }
}
