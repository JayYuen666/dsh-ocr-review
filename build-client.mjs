#!/usr/bin/env node
// @ts-check
/// <reference types="node" />
// 构建 client.js：rolldown 把 src/client-entry.ts 打包为 CJS（react / zod 精确外置），再包进
// window.__ModuleLoader__.load({ id, factory }) 这层 UMD 外壳。id 取 package.json 的 name，
// 与 dsh.client 模块表键一致。
// 编排（哪些依赖要外部化、store 路径折叠（collapseStorePaths）、外壳 拼装）统一实现在
// @jayyuen66/dsh-plugin-shared/lib/build-client；本文件只声明入口、生成头与本仓自有的包名同源校验。
// 运行：node build-client.mjs（或 pnpm build:client）。buildClient() 供测试导入。
import path from "node:path";
import { rolldown } from "rolldown";
import {
  buildClientBundle,
  REACT_RUNTIME_MODULES,
} from "@jayyuen66/dsh-plugin-shared/lib/build-client";
import { invokedDirectly, writeArtifact } from "@jayyuen66/dsh-plugin-shared/lib/build-artifacts";

const root = import.meta.dirname;

// 外置清单 = shared 已发布的 REACT_RUNTIME_MODULES + zod（宿主 `PLATFORM_MODULES` 里本卡
// 值导入的第三方运行时）。基座只能取已发布的导出：消费者 CI 装的是 registry 上那份 shared，
// 未发布的符号在它发布之前不存在。zod 内联会打进每份 client.js，并让同一页面出现两份 zod 身份。
//
// shared 的 `./client` 由 cordis.patch.yml 插入的固定 id（`dsh-plugin-shared`）供应行装载成模块表条目；
// package.json 的 dsh.client.external 同步声明这一条，供宿主按依赖边排序。
// 历史教训：只作为传递依赖安装、宿主没把 shared 排进启动图时，页面启动会落进
// "missed the module table"（GitHub issue #2，宿主 0.2.2-rc.1 dsh desktop）。
// 本仓现在显式启用供应行，并接受「shared 必须作为 client row 被宿主装载」这一前提。
const CLIENT_EXTERNALS = [...REACT_RUNTIME_MODULES, "zod", "@jayyuen66/dsh-plugin-shared/client"];

/** 生成 client.js 的完整文本（含 ModuleLoader 外壳）。 */
export async function buildClient() {
  return buildClientBundle({
    root,
    rolldown,
    externals: CLIENT_EXTERNALS,
    minify: true,
    header:
      "// GENERATED by buildClient() in build-client.mjs — edit src/client-entry.ts, then run `node build-client.mjs`.",
    verifyName: async ({ pkgName, readSource }) => {
      // 槽 key、descriptor id 与 `$mount` 的 package 位都引用 lib/remote-shape.ts 的
      // OCR_BUNDLE_PACKAGE。压缩会 mangle 标识符、也可能内联常量，判据改读源码声明。
      const shape = await readSource(path.join("lib", "remote-shape.ts"));
      const { literal } =
        /(?:const|let|var)\s+OCR_BUNDLE_PACKAGE\s*=\s*(?<literal>"(?:[^"\\]|\\.)*")/u.exec(shape)
          ?.groups ?? {};
      if (!literal) {
        throw new Error(
          "build-client：lib/remote-shape.ts 里找不到 OCR_BUNDLE_PACKAGE 的字面量声明。",
        );
      }
      if (JSON.parse(literal) !== pkgName) {
        throw new Error(
          `build-client：lib/remote-shape.ts 的 OCR_BUNDLE_PACKAGE 是 ${literal}，` +
            `package.json 的 name 是 ${JSON.stringify(pkgName)}——两者不同源。`,
        );
      }
      const entrySource = await readSource(path.join("src", "client-entry.ts"));
      const entry = entrySource
        .replaceAll(/\/\*[\s\S]*?\*\//gu, "")
        .replaceAll(/^\s*\/\/.*$/gmu, "");
      if (entry.includes(JSON.stringify(pkgName))) {
        throw new Error(
          "build-client：src/client-entry.ts 里又内联了一份包名字面量；包名必须收敛到 lib/remote-shape.ts 的 OCR_BUNDLE_PACKAGE。",
        );
      }
    },
  });
}

async function main() {
  const out = await buildClient();
  await writeArtifact(path.join(root, "client.js"), out);
  console.info("client.js written:", Buffer.byteLength(out, "utf8"), "bytes");
}

if (invokedDirectly(import.meta.filename)) {
  try {
    await main();
  } catch (error) {
    console.error(error);
    process.exitCode = 1;
  }
}
